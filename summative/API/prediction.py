"""Online-Breach Impact Estimator API.

Predicts how many records were probably exposed in an online-threat security incident
(hacking, malware or social engineering), using the Random Forest pipeline saved by
linear_regression/multivariate.ipynb.

Routes
    GET  /         short service description
    POST /predict  incident details in, predicted records exposed out
    POST /retrain  upload a CSV of new incidents; the model is retrained and used at once
    GET  /docs     Swagger UI (generated by FastAPI)

Run locally:   uvicorn prediction:app --reload        (from the summative/API folder)
Run on Render: uvicorn prediction:app --host 0.0.0.0 --port $PORT
"""

import io
import os
import threading
from pathlib import Path
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, ValidationError
from sklearn.base import clone
from sklearn.linear_model import SGDRegressor
from sklearn.metrics import mean_squared_error

API_DIR = Path(__file__).resolve().parent
MODEL_PATH = API_DIR / "best_model.pkl"
TRAINING_DATA_PATH = API_DIR / "training_data.csv"
RETRAINED_PATH = API_DIR / "retrained_model.pkl"  # git-ignored; the repo copy of best_model.pkl is never overwritten

NUMERIC = ["incident_year", "num_action_types", "num_data_types"]
CATEGORICAL = ["action_type", "actor_motive", "actor_variety", "hacking_vector", "data_type",
               "discovery_method", "employee_count", "industry", "region"]
FEATURES = NUMERIC + CATEGORICAL
TARGET = "records_exposed"

# --------------------------------------------------------------------------------------
# Request / response schemas
# Every field has an enforced type. Numeric fields have realistic ranges; text fields only
# accept the categories the model was trained on (VERIS framework values). Anything else
# returns a 422 validation error instead of a prediction.
# --------------------------------------------------------------------------------------
ActionType = Literal["Hacking", "Malware", "Social"]
ActorMotive = Literal["Financial", "Espionage", "Ideology", "Grudge", "Fun", "Fear", "Secondary", "Unknown"]
ActorVariety = Literal["Organized crime", "Unaffiliated", "Activist", "Nation-state", "State-affiliated",
                       "Former employee", "Competitor", "Acquaintance", "Customer", "Terrorist", "Unknown"]
HackingVector = Literal["Web application", "Backdoor", "Partner", "VPN", "Desktop sharing",
                        "Desktop sharing software", "3rd party desktop", "Physical access", "Command shell", "Unknown"]
DataType = Literal["Personal", "Credentials", "Medical", "Payment", "Bank", "Internal", "Classified",
                   "Sensitive Personal", "Virtual currency", "Secrets", "Digital certificate", "Copyrighted", "Unknown"]
DiscoveryMethod = Literal["External", "Internal", "Partner", "Unknown"]
EmployeeCount = Literal["1 to 10", "11 to 100", "101 to 1000", "1001 to 10000", "10001 to 25000",
                        "25001 to 50000", "50001 to 100000", "Over 100000", "Small", "Large", "Unknown"]
Industry = Literal["Accommodation", "Administrative", "Agriculture", "Construction", "Education", "Entertainment",
                   "Finance", "Healthcare", "Information", "Management", "Manufacturing", "Mining",
                   "Other Services", "Professional Services", "Public Administration", "Real Estate", "Retail",
                   "Transportation", "Utilities", "Wholesale", "Unknown"]
Region = Literal["Africa", "Americas", "Asia", "Europe", "Oceania", "Unknown"]


class BreachIncident(BaseModel):
    """What an incident-response team knows about an online attack at detection time."""

    model_config = ConfigDict(
        extra="forbid",  # reject misspelled / unknown field names
        json_schema_extra={"examples": [{
            "incident_year": 2025, "num_action_types": 1, "num_data_types": 2,
            "action_type": "Hacking", "actor_motive": "Financial", "actor_variety": "Organized crime",
            "hacking_vector": "Web application", "data_type": "Personal", "discovery_method": "External",
            "employee_count": "1001 to 10000", "industry": "Finance", "region": "Africa",
        }]},
    )

    incident_year: int = Field(..., ge=2005, le=2030, description="Year the incident happened (2005-2030)")
    num_action_types: int = Field(..., ge=1, le=7,
                                  description="How many VERIS action categories were involved (1-7), e.g. hacking + malware = 2")
    num_data_types: int = Field(..., ge=0, le=15,
                                description="How many kinds of data were stolen (0-15), e.g. names + passwords = 2; 0 if not yet known")
    action_type: ActionType = Field(..., description="Main attack type")
    actor_motive: ActorMotive = Field(..., description="Attacker's motive")
    actor_variety: ActorVariety = Field(..., description="Kind of external attacker")
    hacking_vector: HackingVector = Field(..., description="Entry point used for hacking")
    data_type: DataType = Field(..., description="Main kind of data compromised")
    discovery_method: DiscoveryMethod = Field(..., description="Who discovered the breach")
    employee_count: EmployeeCount = Field(..., description="Size of the victim organisation")
    industry: Industry = Field(..., description="Victim's industry")
    region: Region = Field(..., description="Victim's world region")


class PredictionResponse(BaseModel):
    predicted_records_exposed: int = Field(..., description="Estimated number of records exposed")
    predicted_log10_records: float = Field(..., description="Model output on the log10 scale")
    severity: str = Field(..., description="Order-of-magnitude band for triage")
    model: str


class TrainingRow(BreachIncident):
    """One row of an uploaded retraining CSV: the 12 inputs plus the known outcome."""

    model_config = ConfigDict(extra="ignore")
    records_exposed: float = Field(..., gt=0, le=1e11, description="Known number of records exposed")


# --------------------------------------------------------------------------------------
# Model loading and prediction (same function as in the notebook)
# --------------------------------------------------------------------------------------
_lock = threading.Lock()
pipeline = joblib.load(MODEL_PATH)  # loaded from the repository at startup
training_data = pd.read_csv(TRAINING_DATA_PATH)


def predict_records_exposed(row: dict, model=None) -> dict:
    """Predict records exposed for one incident with the saved pipeline (loaded from disk if no model given)."""
    model = model if model is not None else joblib.load(MODEL_PATH)
    log_pred = float(model.predict(pd.DataFrame([row])[FEATURES])[0])
    return {"predicted_log10_records": round(log_pred, 3),
            "predicted_records_exposed": int(round(10 ** log_pred))}


def severity_band(records: int) -> str:
    if records < 1_000:
        return "Low (under 1,000 records)"
    if records < 100_000:
        return "Moderate (1,000 - 100,000 records)"
    if records < 10_000_000:
        return "High (100,000 - 10 million records)"
    return "Critical (over 10 million records)"


# --------------------------------------------------------------------------------------
# App + CORS
# --------------------------------------------------------------------------------------
app = FastAPI(
    title="Online-Breach Impact Estimator",
    description=("Predicts how many records an online-threat incident (hacking, malware, phishing) probably "
                 "exposed, so incident responders can size notifications and escalation before forensics "
                 "confirms the real count. Trained on the Verizon VERIS Community Database (VCDB)."),
    version="1.0.0",
)

# CORS: which *websites* (browser origins) may call this API.
# ALLOWED: only the origins listed below:
#   - this service's own public Render URL (RENDER_EXTERNAL_URL is set automatically by Render), so the
#     Swagger UI at /docs works;
#   - the local Flutter web debug server (run it with: flutter run -d chrome --web-port 5000);
#   - any extra origins given in the EXTRA_ALLOWED_ORIGINS env var (comma-separated), without a code change.
# RESTRICTED:
#   - no wildcard "*": an unknown website cannot make a visitor's browser call this API;
#   - methods: only GET (docs, info) and POST (/predict, /retrain), the only verbs the API uses;
#   - headers: only Content-Type and Accept, which JSON requests and file uploads need (no auth headers);
#   - credentials: False, because the API uses no cookies or sessions, so browsers send none.
# The Flutter mobile app is not a browser, so CORS does not apply to it; it calls the API directly.
ALLOWED_ORIGINS = [
    "http://localhost:5000",
    "http://127.0.0.1:5000",
    "http://localhost:8000",  # Swagger UI when the API runs locally
    "http://127.0.0.1:8000",
]
if os.getenv("RENDER_EXTERNAL_URL"):
    ALLOWED_ORIGINS.append(os.environ["RENDER_EXTERNAL_URL"].rstrip("/"))
ALLOWED_ORIGINS += [o.strip().rstrip("/") for o in os.getenv("EXTRA_ALLOWED_ORIGINS", "").split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


@app.get("/", tags=["info"])
def root():
    return {"service": app.title, "docs": "/docs", "model": type(pipeline[-1]).__name__,
            "training_rows": len(training_data), "allowed_origins": ALLOWED_ORIGINS}


@app.post("/predict", response_model=PredictionResponse, tags=["prediction"])
def predict(incident: BreachIncident):
    with _lock:
        model = pipeline
    result = predict_records_exposed(incident.model_dump(), model=model)
    return PredictionResponse(**result, severity=severity_band(result["predicted_records_exposed"]),
                              model=type(model[-1]).__name__)


@app.post("/retrain", tags=["retraining"])
async def retrain(file: UploadFile = File(..., description="CSV with the 12 input columns plus records_exposed")):
    """Upload new incidents; the model is retrained immediately and /predict uses it from then on.

    * SGDRegressor: training continues on the new rows with partial_fit.
    * Any other model (the deployed Random Forest): refit on the original data plus the new rows.
    """
    global pipeline, training_data

    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")
    try:
        new = pd.read_csv(io.BytesIO(await file.read()))
    except Exception as exc:  # unreadable / empty file
        raise HTTPException(status_code=400, detail=f"Could not read the CSV: {exc}")

    missing = [c for c in FEATURES + [TARGET] if c not in new.columns]
    if missing:
        raise HTTPException(status_code=400, detail=f"CSV is missing columns: {missing}. "
                                                    f"Expected: {FEATURES + [TARGET]}")

    # Validate every row with the same rules as /predict; keep the valid ones.
    valid, errors = [], []
    for i, rec in enumerate(new[FEATURES + [TARGET]].to_dict(orient="records"), start=2):  # line 1 = header
        try:
            valid.append(TrainingRow(**{k: (None if pd.isna(v) else v) for k, v in rec.items()}).model_dump())
        except ValidationError as exc:
            errors.append({"csv_line": i, "error": exc.errors()[0]["msg"], "field": exc.errors()[0]["loc"]})
    if not valid:
        raise HTTPException(status_code=422, detail={"message": "No valid rows to train on.", "errors": errors[:20]})

    new_df = pd.DataFrame(valid)[FEATURES + [TARGET]]
    X_new, y_new = new_df[FEATURES], np.log10(new_df[TARGET])

    with _lock:
        old_pipeline = pipeline
        mse_before = mean_squared_error(y_new, old_pipeline.predict(X_new))
        if isinstance(old_pipeline[-1], SGDRegressor):
            updated = old_pipeline  # keep training the same model on the new rows
            X_t = updated[:-1].transform(X_new)
            for _ in range(20):
                updated[-1].partial_fit(X_t, y_new)
            combined = pd.concat([training_data, new_df], ignore_index=True)
            strategy = "partial_fit (SGDRegressor) on the new rows"
        else:
            combined = pd.concat([training_data, new_df], ignore_index=True)
            updated = clone(old_pipeline)  # same preprocessing + hyperparameters, fresh fit
            updated.fit(combined[FEATURES], np.log10(combined[TARGET]))
            strategy = f"refit {type(old_pipeline[-1]).__name__} on original data + new rows"
        mse_after = mean_squared_error(y_new, updated.predict(X_new))

        pipeline, training_data = updated, combined  # /predict uses the new model from now on
        joblib.dump(updated, RETRAINED_PATH, compress=3)

    return {
        "message": "Model retrained and now in use by /predict.",
        "strategy": strategy,
        "rows_received": len(new),
        "rows_used": len(new_df),
        "rows_rejected": len(errors),
        "rejected_examples": errors[:10],
        "total_training_rows": len(combined),
        "mse_on_new_rows_before": round(float(mse_before), 4),
        "mse_on_new_rows_after": round(float(mse_after), 4),
        "note": "On Render's free plan the retrained model is lost when the service restarts; "
                "it then reloads best_model.pkl from the repository.",
    }
